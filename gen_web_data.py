"""
Generate the browser demo's data file.

Writes web/devbot-data.js with the same intents.json the Python bot reads,
plus scikit-learn's English stop-word list and the THRESHOLD from
chatbot.py, so the browser DevBot matches questions exactly like the
Python one. Run it again whenever intents.json changes:

    python gen_web_data.py
"""

import json
from pathlib import Path

from sklearn.feature_extraction.text import ENGLISH_STOP_WORDS

from chatbot import THRESHOLD

HERE = Path(__file__).parent
OUT_FILE = HERE / "web" / "devbot-data.js"


def main() -> None:
    intents = json.loads((HERE / "intents.json").read_text(encoding="utf-8"))
    OUT_FILE.parent.mkdir(exist_ok=True)
    with OUT_FILE.open("w", encoding="utf-8") as file:
        file.write("// Generated by gen_web_data.py from intents.json - do not edit by hand.\n")
        file.write(f"const INTENTS = {json.dumps(intents, indent=2, ensure_ascii=False)};\n")
        file.write(f"const SKLEARN_STOP_WORDS = {json.dumps(sorted(ENGLISH_STOP_WORDS))};\n")
        file.write(f"const THRESHOLD = {THRESHOLD};\n")
    print(f"Wrote {OUT_FILE}")


if __name__ == "__main__":
    main()
